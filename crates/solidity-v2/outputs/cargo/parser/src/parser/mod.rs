/// Ambient state the grammar's actions need.
///
/// These are bundled into a single struct and threaded through the grammar as
/// one `&mut Ctx` parameter, rather than as several separate parameters. LALRPOP
/// forwards grammar parameters through every reduction, so passing a single
/// pointer (and dereferencing its fields only where needed) keeps the hot
/// reduction path cheap.
pub(crate) struct GrammarCtx<'a> {
    /// Source text being parsed (consumed by terminal constructors).
    pub source: &'a str,
    /// Id of the file being parsed, used when reporting diagnostics.
    pub file_id: &'a FileId,
    /// Diagnostics accumulated during parsing.
    pub diagnostics: DiagnosticCollection,
    /// Version being parsed, for diagnostics that depend on which syntax it allows.
    pub language_version: LanguageVersion,
    /// The `NatSpec` comments read by the lexer, until the documentable nodes take them.
    pub natspec_comments: NatSpecConsumer<'a>,
}

impl GrammarCtx<'_> {
    /// See [`NatSpecConsumer::take`].
    pub(crate) fn take_natspec(&self, start: usize, end: usize) -> Option<NatSpec> {
        self.natspec_comments.take(start, end)
    }
}

/// The output of a parse operation, containing both the source unit and any diagnostics.
#[derive(Debug, PartialEq)]
pub struct ParseOutput {
    pub source_unit: SourceUnit,
    pub diagnostics: DiagnosticCollection,
}

/// A Parser for Solidity Source Units
///
/// TODO(v2): Error recovery, for now we return an empty [`SourceUnit`] on error
/// TODO(v2): Make the parser skip unique tokens, performance improvement
#[derive(Default)]
pub struct Parser;

impl Parser {
    pub fn parse(file_id: &FileId, source: &str, language_version: LanguageVersion) -> ParseOutput {
        let natspec_comments = NatSpecComments::default();
        let (natspec_producer, natspec_consumer) = natspec_comments.split();
        let tokens = TokenStream {
            lexer: Lexer::new(source, language_version),
            natspec_comments: natspec_producer,
        };
        let parser = grammar::SourceUnitParser::new();

        let mut ctx = GrammarCtx {
            source,
            file_id,
            diagnostics: DiagnosticCollection::default(),
            language_version,
            natspec_comments: natspec_consumer,
        };

        let source_unit = match parser.parse(&mut ctx, tokens) {
            Ok(source_unit) => {
                // Most validation happens during the 'CompilationUnit' building, but this specific
                // check is done here to make sure that other 'Parser' users can still be informed of any
                // inconsistency between the source unit and the expected syntax version.
                validate_syntax_version(
                    &source_unit,
                    language_version,
                    file_id,
                    &mut ctx.diagnostics,
                );

                source_unit
            }
            Err(e) => {
                convert_parse_error(file_id, &mut ctx.diagnostics, e);

                new_source_unit(new_source_unit_members(vec![]))
            }
        };

        ParseOutput {
            source_unit,
            diagnostics: ctx.diagnostics,
        }
    }
}

/// Convert a LALRPOP parse error into a `DiagnosticCollection`.
fn convert_parse_error(
    file_id: &FileId,
    diagnostics: &mut DiagnosticCollection,
    value: lalrpop_util::ParseError<usize, LexemeKind, ()>,
) {
    /// This function transforms the `String` representation returned by LALRPOP into an instance of `LexemeKind`
    ///
    /// TODO(v2): We may be able to improve on this if there's room for returning a discriminant instead of a string representation.
    /// [Ongoing discussion](https://github.com/lalrpop/lalrpop/issues/1089#issuecomment-4011323139)
    fn convert_expectations(expected: &[String]) -> SortedSet<TerminalKind> {
        expected
            .iter()
            .map(|str| str.strip_prefix("L_").unwrap())
            .map(|str| str.parse::<LexemeKind>().unwrap())
            .map(|lexeme| TerminalKind::from(&lexeme))
            .collect()
    }

    match value {
        lalrpop_util::ParseError::UnrecognizedEof { location, expected } => {
            diagnostics.push(
                file_id.to_owned(),
                location..location,
                UnexpectedEof {
                    expected: convert_expectations(&expected),
                },
            );
        }
        lalrpop_util::ParseError::UnrecognizedToken {
            token: (left, lexeme, right),
            expected,
        } => {
            diagnostics.push(
                file_id.to_owned(),
                left..right,
                UnexpectedTerminal {
                    found: TerminalKind::from(&lexeme),
                    expected: convert_expectations(&expected),
                },
            );
        }
        lalrpop_util::ParseError::ExtraToken { .. } => unreachable!(
            "The parser should never return an extra token error: the top-level `SourceUnit` rule is a greedy repetition"
        ),
        lalrpop_util::ParseError::User { .. } => unreachable!(
            "The parser should never return a user error, since we're not using any custom error types in our grammar"
        ),
        lalrpop_util::ParseError::InvalidToken { .. } => unreachable!(
            "The parser should never return an invalid token error, since it's not using the default lexer"
        ),
    }
}

/// The lexemes fed to the parser, with their offsets.
///
/// Trivia is skipped, but `NatSpec` comments are recorded with the token they document.
///
/// TODO(v2): Include the trivia in future versions
struct TokenStream<'source, 'comments> {
    lexer: Lexer<'source>,
    natspec_comments: NatSpecProducer<'comments>,
}

impl Iterator for TokenStream<'_, '_> {
    type Item = Result<(usize, LexemeKind, usize), ()>;

    fn next(&mut self) -> Option<Self::Item> {
        // Kept lean for LALRPOP's parsing loop: the pending comment is stored in
        // `NatSpecProducer` rather than in a local, and only a bool tracks whether this call saw one.
        let mut after_natspec_comment = false;

        while let Some(lexeme) = self.lexer.next_lexeme() {
            if lexeme.kind.is_natspec_comment() {
                self.natspec_comments.push(lexeme.range.clone());
                after_natspec_comment = true;
            }
            if !lexeme.kind.is_trivia() {
                if after_natspec_comment {
                    self.natspec_comments.document(lexeme.range.start);
                }
                return Some(Ok((lexeme.range.start, lexeme.kind, lexeme.range.end)));
            }
        }
        None
    }
}
